  function play(position,moves){
    var tokens=position.split(' ');
    moves.forEach(function(m){
      var from=m.slice(0,2),to=m.slice(2,4);
      tokens=tokens.filter(function(t){return t.split(':')[1]!==to;}).map(function(t){var p=t.split(':');return p[1]===from?p[0]+':'+to:t;});
    });
    return tokens.join(' ');
  }
  function after(moves){return play(START,moves);}
  // Teaching steps that follow one game on one board: each entry is [text, move or null, marks]; a move ('e3e4') is
  // played on the board of the step before, so the learner sees one move at a time and the position never jumps.
  function line(position,entries){
    return entries.map(function(e){if(e[1])position=play(position,[e[1]]);return step(e[0],position,e[2]);});
  }
