'use strict';
// Builds ai/index.html, the stand-alone page for testing the hard AI (https://natstpt.github.io/makrukthai/ai):
// editor.html with <base href="../"> (so every file, the engine and coi-sw.js load from the site root) and
// window.MAKRUK_PAGE = 'ai' (editor.js then plays the hard AI only, outside the lessons).
// Run: node scripts/build-ai-page.cjs (tests/ai-page.test.cjs checks the page is up to date).
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
function build() {
  let html = fs.readFileSync(path.join(root, 'editor.html'), 'utf8');
  const head = '<meta charset="utf-8">';
  if (!html.includes(head)) throw Error('editor.html: no <meta charset> to put the base after');
  html = html.replace(head, head + '<base href="../"><script>window.MAKRUK_PAGE=\'ai\';</script>');
  html = html.replace(/<title>[^<]*<\/title>/, '<title>เล่นกับ AI ระดับยาก | Makruk Learn</title>');
  return html.replace(/^(<!doctype html>\n?)/i, '$1<!-- Generated by scripts/build-ai-page.cjs from editor.html — do not edit by hand. -->\n');
}
if (require.main === module) { fs.writeFileSync(path.join(root, 'ai', 'index.html'), build()); console.log('ai/index.html written.'); }
module.exports = { build };
