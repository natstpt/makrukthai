'use strict';
// Builds chase-trees.js: the red king's replies for every long chase (ไล่ยาว) in the endgame chapter.
// Run: node scripts/build-chase-trees.cjs   (set MAKRUK_TABLEBASE_DIR to keep the tablebases between runs;
// the four-piece tables take several minutes each to build).
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { chaseTree } = require('./chase-tree.cjs');

const repo = path.join(__dirname, '..');
const context = { window: {} };
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(repo, 'endgame-lessons.js'), 'utf8'), context);
const cache = new Map(), trees = {};
for (const lesson of context.window.buildEndgameLessons()) {
  if (!lesson.puzzle) continue;
  for (const task of lesson.games) {
    if (!task.chase) continue;
    const pieces = JSON.parse(JSON.stringify(task.pieces));
    // White may use every move the counting rule allows: red counts from pieces + 1 up to the ceiling.
    const countMoves = task.count.ceiling - task.count.start + 2;
    if (task.moves > countMoves) throw new Error(`${task.key}: ${task.moves} moves is more than the count allows (${countMoves})`);
    const { dtm, nodes } = chaseTree(pieces, task.moves, cache);
    if (task.moves - dtm > 1) throw new Error(`${task.key}: mate in ${dtm} but ${task.moves} moves allowed; keep at most one spare move`);
    trees[task.key] = { dtm, nodes };
    console.log(task.key, 'mate in', dtm, 'allowed', task.moves, 'nodes', nodes.length);
  }
}
const out = '/* Generated by scripts/build-chase-trees.cjs — do not edit by hand.\n' +
  '   Long chases: dtm = fastest mate; nodes[i] lists accepted white moves as "from-to" + "#" or red reply + next node (base 36). */\n' +
  '(function(root){root.MakrukChaseTrees=' + JSON.stringify(trees) + ';})(typeof window===\'object\'?window:globalThis);\n';
fs.writeFileSync(path.join(repo, 'chase-trees.js'), out);
console.log('chases', Object.keys(trees).length, 'bytes', out.length);
