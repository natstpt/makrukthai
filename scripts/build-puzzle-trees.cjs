'use strict';
// Builds puzzle-trees.js: the moves the red king plays in every short puzzle (กลสั้น) of the endgame chapter.
// Run: node scripts/build-puzzle-trees.cjs
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { createSolver } = require('./puzzle-solver.cjs');

const repo = path.join(__dirname, '..');
const context = { window: {} };
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(repo, 'endgame-lessons.js'), 'utf8'), context);
const solver = createSolver();
const trees = {};
for (const lesson of context.window.buildEndgameLessons()) {
  if (!lesson.puzzle) continue;
  for (const task of lesson.games) {
    const pieces = JSON.parse(JSON.stringify(task.pieces));
    const found = solver.depth(pieces, task.moves);
    if (found !== task.moves) throw new Error(`${task.key}: mate in ${found}, expected ${task.moves}`);
    trees[task.key] = solver.solutionTree(pieces, task.moves, task.line);
  }
}
const out = '/* Generated by scripts/build-puzzle-trees.cjs — do not edit by hand.\n' +
  '   For each short puzzle: white moves that still mate in time → red reply (r) and the next node (n); "#" is mate. */\n' +
  '(function(root){root.MakrukPuzzleTrees=' + JSON.stringify(trees) + ';})(typeof window===\'object\'?window:globalThis);\n';
fs.writeFileSync(path.join(repo, 'puzzle-trees.js'), out);
console.log('puzzles', Object.keys(trees).length, 'bytes', out.length);
